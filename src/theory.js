  /* ===== 押し引き基準 =====
     リーチに対して真っ向から押してよいのは聴牌時。
     1向聴は基本1枚押しまで（高打点かつ好形なら巡目に応じて押せる）。
     2向聴以下は即ベタオリ。終盤は許容放銃率が下がり、最終盤は形式聴牌のため再び押し有利（U字）。 */
  function allowedRisk(shanten, goodShape, bigValue, go, wallLeft) {
    if (shanten >= 2) return 0.01;           // 現物のみ
    if (shanten === 0) return 1;             // 聴牌は押し
    // 1向聴
    var base;
    if (bigValue && goodShape) base = 0.18;
    else if (bigValue || goodShape) base = 0.10;
    else base = 0.06;
    if (go >= 14) base = Math.min(base, 0.05);
    else if (go >= 10) base = Math.min(base, 0.10);
    if (wallLeft != null && wallLeft <= 8) base = Math.max(base, 0.08); // 形式聴牌狙い(U字の戻り)
    return base;
  }

