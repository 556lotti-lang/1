  function ceilRon(x, iAmDealer) {
    var tbl = iAmDealer ? DEALER_RON : CHILD_RON;
    for (var i = 0; i < tbl.length; i++) if (x <= tbl[i]) return tbl[i];
    return tbl[tbl.length - 1];
  }

